import { normalizeIcsDate } from '../utils/icsDate';

describe('normalizeIcsDate', () => {
  test.each([
    ['20261018', '20261018'],
    ['2026-10-18', '20261018'],
    ['2026.10.18', '20261018'],
    ['2026/1/8', '20260108'],
    ['2026-10-18 14:30', '20261018T143000'],
    ['2026-10-18 1430', '20261018T143000'],
    ['2026-10-18T14:30:15', '20261018T143015'],
    ['20261018T143000', '20261018T143000'],
    ['20261018T143000Z', '20261018T143000Z'],
    ['2024-02-29', '20240229'],
  ])('%s → %s', (input, expected) => {
    expect(normalizeIcsDate(input)).toBe(expected);
  });

  test.each(['', null, undefined, 'abc', '2026-13-01', '2026-02-30', '2025-02-29', '2026-10-18 25:00', '2026-10-18 10:61', '20261332'])(
    '해석할 수 없는 값 %p → null',
    (input) => {
      expect(normalizeIcsDate(input)).toBeNull();
    }
  );
});
